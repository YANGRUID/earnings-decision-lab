"""Options Decision Engine V4.3.1 -- Strike Geometry Candidate Sets
(2026-09-03).

V4.3 constructs exactly ONE deterministic geometry per strategy (e.g.
a long call always targets the full expected-move boundary). That is
more economically grounded than V3's ATM-index method, but it is not
yet evidence that one exact normalized strike distance is optimal
under the real T+1 benchmark -- that comparison is V4.4's job, not
built here (this task's own Section 0/14/23).

This module adds a bounded set of economically meaningful ALTERNATIVE
geometries per strategy -- never a blind grid applied uniformly (each
strategy's variants are justified by that strategy's own real payoff
economics, documented per generator below), never fit to the 7 real
settled losses (Section 22), and never scored or ranked (V4.4's job).
V4.3's own base geometry is always included, unmodified, as the
canonical/BASE variant -- this module is purely additive.

CANDIDATE BUDGET (Section 15): at most ``MAX_VARIANTS_PER_STRATEGY``
variants per strategy family, enforced by construction (every
generator below returns a fixed-length tuple, verified by a static
test against this constant) -- never combinatorial explosion.

CONTRACT DEDUPLICATION (Section 16): ``required_unique_contracts`` on
the returned ``StrikeGeometryCandidateSet`` is the deduplicated
(right, strike) set across every variant's legs -- e.g. three long-call
variants sharing no strikes still report 3 contracts, but two credit-
spread wing variants sharing the same short leg report only the wing
strikes as distinct, the short leg once.

TEMPORAL COHERENCE (Section 17): every variant generated by one call
to ``generate_strike_geometry_variants`` shares the SAME
``ExpectedMoveContext`` (one ``observed_at``) and the SAME real
``quotes`` list (one point-in-time snapshot) -- structurally, not by
convention, since every variant generator below receives exactly
those two shared objects and constructs nothing else. This is the
"bounded batch quote strategy" this task's own Section 17 asks for:
one shared snapshot per candidate-set-generation call, deduplicated
contracts requested together, never variant A quoted at T0 and
variant Z quoted minutes later.
"""

