# --------------------------------------------------------------------------
# LONG_STRADDLE -- no meaningful variant dimension exists (Section 12's
# own principle applied generally: "only include variants if
# economically justified"). A straddle's whole point is sharing one
# ATM strike; there is no distance parameter to vary without ceasing
# to be a straddle. One variant only, which is also the base.
# --------------------------------------------------------------------------


def _build_long_straddle_variants(
    context: ExpectedMoveContext, quotes: list[OptionQuote]
) -> tuple[StrikeGeometryVariant, ...]:
    semantics = "Nearest coherent-spot strike -- shared by both legs; V4.3's own base geometry."
    target = context.spot
    rationale = (
        "Nearest coherent-spot strike -- shared by both legs of a two-sided convex structure."
    )
    call_leg = build_leg("buy", "call", target, rationale, quotes, context)
    put_leg = build_leg("buy", "put", target, rationale, quotes, context)
    if call_leg.selected_strike is None or put_leg.selected_strike is None:
        result = unconstructable_result(
            StrategyCategory.LONG_STRADDLE,
            context,
            [UNCONSTRUCTABLE_MISSING_LEG_QUOTE],
            "Real chain lacks a quoted call or put near coherent spot.",
            legs=(call_leg, put_leg),
        )
        return (StrikeGeometryVariant("long_straddle_BASE", semantics, result, True),)
    if call_leg.selected_strike != put_leg.selected_strike:
        result = unconstructable_result(
            StrategyCategory.LONG_STRADDLE,
            context,
            ["UNCONSTRUCTABLE_SHARED_CENTER_MISMATCH"],
            f"Nearest-ATM call strike {call_leg.selected_strike} and put strike "
            f"{put_leg.selected_strike} differ.",
            legs=(call_leg, put_leg),
        )
        return (StrikeGeometryVariant("long_straddle_BASE", semantics, result, True),)
    center = call_leg.selected_strike
    result = V4StrikeSelectionResult(
        strategy=StrategyCategory.LONG_STRADDLE,
        status="constructed",
        spot=context.spot,
        expected_move_context=context,
        legs=(call_leg, put_leg),
        center_target=target,
        lower_boundary=None,
        upper_boundary=None,
        width=Decimal(0),
        width_pct_of_spot=Decimal(0),
        width_in_expected_move_units=Decimal(0),
        symmetry_error_pct=Decimal(0),
        reason_codes=tuple(dict.fromkeys([*call_leg.reason_codes, *put_leg.reason_codes])),
        explanation=f"Long straddle centered at real ATM strike {center} (spot {context.spot}).",
        engine_version=STRIKE_ENGINE_VERSION,
    )
    return (StrikeGeometryVariant("long_straddle_BASE", semantics, result, True),)


