def generate_strike_geometry_variants(
    strategy: StrategyCategory,
    context: ExpectedMoveContext,
    quotes: list[OptionQuote],
    *,
    filter_mode: FilterMode = "ALL_CANDIDATES",
    market_view: V4MarketView | None = None,
    chain_metadata: ChainMetadata | None = None,
) -> StrikeGeometryCandidateSet:
    """The one dispatcher every V4.3.1 caller uses. ``filter_mode``
    (Section 19) is diagnostic only -- SEMANTICALLY_PLAUSIBLE_ONLY
    skips variant generation entirely for a strategy V4.2's own
    compatibility engine finds an outright CONTRADICTION for the
    given ``market_view``, never a partial/ranking filter, and never
    the default (ALL_CANDIDATES is). This is NOT the official ranking
    policy (Section 19's own explicit instruction)."""
    if filter_mode == "SEMANTICALLY_PLAUSIBLE_ONLY" and market_view is not None:
        semantics = get_strategy_semantics(strategy)
        compatibility = evaluate_semantic_compatibility(market_view, semantics)
        if compatibility.overall_semantic_compatibility <= CONTRADICTION:
            skipped_result = unconstructable_result(
                strategy,
                context,
                [SKIPPED_SEMANTIC_CONTRADICTION],
                f"Variant generation skipped (SEMANTICALLY_PLAUSIBLE_ONLY): "
                f"{compatibility.explanation}",
            )
            skipped_variant = StrikeGeometryVariant(
                f"{strategy.value}_SKIPPED",
                "Skipped: outright V4.2 semantic contradiction.",
                skipped_result,
                True,
            )
            return StrikeGeometryCandidateSet(
                strategy=strategy,
                base_geometry=skipped_variant,
                variants=(skipped_variant,),
                required_unique_contracts=(),
                coverage_status="0/0 constructed (filtered: semantic contradiction)",
                chain_metadata_status=_chain_metadata_status_text(chain_metadata),
                candidate_generation_version=GEOMETRY_CANDIDATE_VERSION,
            )

    variants = _VARIANT_GENERATORS[strategy](context, quotes)
    base_geometry = next(v for v in variants if v.is_base_geometry)
    constructed = sum(1 for v in variants if v.result.status == "constructed")
    return StrikeGeometryCandidateSet(
        strategy=strategy,
        base_geometry=base_geometry,
        variants=variants,
        required_unique_contracts=_dedupe_contracts(variants),
        coverage_status=f"{constructed}/{len(variants)} constructed",
        chain_metadata_status=_chain_metadata_status_text(chain_metadata),
        candidate_generation_version=GEOMETRY_CANDIDATE_VERSION,
    )


def generate_all_strategy_variant_sets(
    context: ExpectedMoveContext,
    quotes: list[OptionQuote],
    *,
    chain_metadata: ChainMetadata | None = None,
) -> dict[StrategyCategory, StrikeGeometryCandidateSet]:
    """Convenience function for the Section 15 candidate-count budget
    demonstration -- generates every strategy's variant set against
    one shared context/quotes (one point-in-time snapshot, Section
    17). Never used by any official pipeline; diagnostic only."""
    return {
        strategy: generate_strike_geometry_variants(
            strategy, context, quotes, chain_metadata=chain_metadata
        )
        for strategy in StrategyCategory
    }
