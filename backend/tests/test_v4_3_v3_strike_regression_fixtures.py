def _to_quotes(decision: dict, raw_chain: list[tuple]) -> tuple[OptionQuote, ...]:
    ticker = decision["ticker"]
    expiration = decision["selected_expiration"]
    observed_at = decision["observed_at"]
    quotes = []
    for (
        strike,
        option_type,
        bid,
        ask,
        last_price,
        volume,
        open_interest,
        iv,
        delta,
        ext_id,
    ) in raw_chain:
        quotes.append(
            OptionQuote(
                source_provider="ibkr",
                retrieved_at=observed_at,
                ticker=ticker,
                snapshot_timestamp=observed_at,
                expiration_date=expiration,
                strike=strike,
                option_type=option_type,
                bid=bid,
                ask=ask,
                last_price=last_price,
                volume=volume,
                open_interest=open_interest,
                implied_volatility=iv,
                delta=delta,
                external_contract_id=ext_id,
            )
        )
    return tuple(quotes)


def _build_input(
    decision: dict, raw_chain: list[tuple], historical_moves: list[Decimal]
) -> V3StrikeReplayInput:
    return V3StrikeReplayInput(
        ticker=decision["ticker"],
        strategy_type=decision["strategy_type"],
        underlying_price=decision["underlying_price"],
        observed_at=decision["observed_at"],
        expiration=decision["selected_expiration"],
        v3_legs=decision["v3_legs"],
        chain_quotes=_to_quotes(decision, raw_chain),
        historical_next_day_move_pcts=tuple(historical_moves),
    )


