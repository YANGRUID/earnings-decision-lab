def test_the_graph_state_has_no_field_that_could_hold_a_secret():
    from agents.graph.state import ResearchState

    # Precise names, not substrings: `input_tokens` and `output_tokens`
    # are usage COUNTS and entirely legitimate, so a bare "token" match
    # would flag the honest fields and say nothing about the real risk.
    forbidden = (
        "api_key",
        "apikey",
        "password",
        "secret",
        "credential",
        "authorization",
        "bearer",
        "access_token",
        "private_key",
        "dsn",
    )
    for field_name in ResearchState.__annotations__:
        lowered = field_name.lower()
        for name in forbidden:
            assert name not in lowered, (
                f"ResearchState.{field_name} must not exist (requirement 91)"
            )
    assert "input_tokens" in ResearchState.__annotations__, (
        "usage counts are legitimate state and must not be removed by over-zealous "
        "pattern matching"
    )


def test_a_node_error_message_is_redacted():
    """A provider error can echo a request URL, and this project's adapters
    authenticate via a query parameter."""
    from agents.graph.nodes import _error

    error = _error(
        "synthesize",
        RuntimeError("GET https://api.example.com/v1?apikey=sk-live-abc123 failed"),
        recoverable=True,
    )
    assert "sk-live-abc123" not in error["message"]
    assert "apikey=REDACTED" in error["message"]


