# --- requirement 16: no execution tool anywhere ------------------------


def test_no_brokerage_execution_tool_exists_in_the_tool_layer():
    for path in sorted((_SRC / "agents").rglob("*.py")):
        text = path.read_text()
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if (
                        isinstance(target, ast.Name)
                        and target.id == "name"
                        and isinstance(node.value, ast.Constant)
                        and isinstance(node.value.value, str)
                    ):
                        value = node.value.value.lower()
                        for fragment in ("order", "exercise", "execute_trade"):
                            assert fragment not in value, (
                                f"{path.name} declares a tool named "
                                f"{node.value.value!r}"
                            )


def test_the_tool_layer_does_not_import_an_order_placing_client():
    """Checked as real imports rather than as substrings: agents/adapters/
    tools.py legitimately CONTAINS these words -- they are its denylist --
    and a substring test would flag the guard as the violation."""
    forbidden_modules = ("ibapi", "providers.ibkr_tws_client", "providers.ibkr_tws_options")
    for path in sorted((_SRC / "agents").rglob("*.py")):
        imported = _imports(str(path.relative_to(_SRC)))
        offending = sorted(
            name
            for name in imported
            for prefix in forbidden_modules
            if name == prefix or name.startswith(f"{prefix}.")
        )
        assert not offending, f"{path.name} imports {offending}"
    # And no agent module calls an order method on anything.
    for path in sorted((_SRC / "agents").rglob("*.py")):
        tree = ast.parse(path.read_text())
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute):
                assert node.attr not in ("placeOrder", "cancelOrder", "exerciseOptions"), (
                    f"{path.name} calls {node.attr}"
                )


# --- requirement 55: one judgement, one verification, no critic chain --


def test_the_graph_has_no_adversarial_roles():
    from agents.graph.workflow import graph_shape

    nodes = graph_shape()["nodes"]
    assert isinstance(nodes, list)
    for forbidden in ("bull", "bear", "critic", "judge", "debate", "adversar"):
        assert not any(forbidden in n for n in nodes), (
            f"a {forbidden!r} node would make this a different methodology"
        )
    # One synthesis, one verification, one bounded revision -- the shape
    # the project already validated.
    assert nodes.count("synthesize") == 1
    assert nodes.count("verify") == 1
    assert nodes.count("revise") == 1
    assert graph_shape()["max_revisions"] == 1


