def test_langsmith_tracing_is_off(monkeypatch):
    """langchain-core pulls langsmith transitively. Tracing would send
    prompts and tool output to a third-party service, so it must be off by
    default and nothing in this codebase may turn it on."""
    from langsmith.utils import tracing_is_enabled

    for var in ("LANGSMITH_TRACING", "LANGCHAIN_TRACING_V2", "LANGSMITH_API_KEY"):
        monkeypatch.delenv(var, raising=False)
    assert tracing_is_enabled() is False
    for path in sorted((_SRC / "agents").rglob("*.py")):
        text = path.read_text()
        assert "LANGSMITH" not in text
        assert "LANGCHAIN_TRACING" not in text
