"""Structural isolation for the agentic research layer
(requirements 78-81, 16, 52, 55, 90).

Same approach as tests/test_v4_4c_shadow_isolation.py: these walk the
real import graph with ``ast`` rather than reading docstrings, so each
guarantee is a checkable fact that fails the moment it stops holding --
which is exactly when a person should be asked, not after the first
forward sample has been contaminated.
"""

import ast
import os
from pathlib import Path

import pytest

_SRC = Path(__file__).resolve().parents[1] / "src"

#: Every module in the agentic research layer.
AGENT_RUNTIME_MODULES = (
    "agents/graph/state.py",
    "agents/graph/deps.py",
    "agents/graph/nodes.py",
    "agents/graph/quality.py",
    "agents/graph/workflow.py",
    "agents/graph/runtime.py",
    "agents/graph/checkpoint.py",
    "agents/adapters/model.py",
    "agents/adapters/tools.py",
    "agents/adapters/structured.py",
    "agents/adapters/retriever.py",
    "agents/runtime.py",
)

#: The deterministic financial engine. Strike geometry, expected move,
#: candidate construction, T+1 valuation, ranking, risk, capital, sizing,
#: entry and settlement. The research layer must not reach ANY of it.
DETERMINISTIC_ENGINE_PREFIXES = (
    "analytics.decision.",
    "analytics.options.strategy_candidates",
    "services.v4_",
    "services.v4_2_",
)

#: Modules that produce official forward evidence. These must not reach
#: either agent runtime (requirement 79).
OFFICIAL_FORWARD_MODULES = (
    "services/v4_shadow_orchestration.py",
    "services/v4_shadow.py",
    "services/v4_shadow_assembler.py",
    "services/v4_shadow_scheduler.py",
    "services/v4_2_challenger.py",
    "services/v4_2_phase2.py",
    "services/v4_2_parallel.py",
)

AGENT_RUNTIME_IMPORT_PREFIXES = ("agents.graph", "agents.adapters", "agents.orchestrator")


def _imports(relative_path: str) -> set[str]:
    """Every module name this file imports, including inside functions --
    this project uses deferred imports heavily, so a module-level-only
    check would miss most of them."""
    tree = ast.parse((_SRC / relative_path).read_text())
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            found.add(node.module)
            found.update(f"{node.module}.{alias.name}" for alias in node.names)
    return found


# --- requirement 78: the graph does not touch the V4 engine ------------


@pytest.mark.parametrize("module", AGENT_RUNTIME_MODULES)
def test_the_research_layer_cannot_reach_the_deterministic_engine(module):
    offending = sorted(
        name
        for name in _imports(module)
        for prefix in DETERMINISTIC_ENGINE_PREFIXES
        if name.startswith(prefix)
    )
    assert not offending, (
        f"{module} imports {offending}. Strikes, expected move, ranking, risk, "
        f"capital, sizing, entry and settlement stay deterministic Python -- the "
        f"research layer produces judgement and evidence, nothing else."
    )


def test_no_agent_module_imports_an_options_pricing_or_sizing_function():
    """Belt and braces on requirement 78: named functions, not just
    package prefixes."""
    forbidden = (
        "black_scholes",
        "max_defined_risk",
        "position_size",
        "choose_v4_2_candidate",
        "rank_candidates",
        "compute_entry_exit_schedule",
    )
    for module in AGENT_RUNTIME_MODULES:
        text = (_SRC / module).read_text()
        for name in forbidden:
            assert name not in text, f"{module} references {name}"


# --- requirement 79: the forward path stays legacy --------------------


